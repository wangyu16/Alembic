/**
 * A14: move a 0.x course (public repo + private repo) into one v3 working
 * tree, for the owners' manual move (R31). Pure planning + conversion; the
 * CLI (`scripts/move-course-v3.ts`) does the file system.
 *
 * - Both trees are merged; the old private repo's files keep their
 *   `private/...` paths, the public repo's keep theirs.
 * - Slides slot files `slides/<slug>.md` become `slides/<slug>.slides.md`.
 * - Every text slot file gets an FC-18 header when it has none (title from
 *   the first heading, uid from the manifest when known).
 * - Self-contained files (`.md.html`, `.slides.html`, `.paged.html`) become
 *   their text (`.md`, `.slides.md`, `.paged.md`) through the 1.x kits'
 *   `extract`, which also reads 0.x files.
 * - Nothing is dropped silently: every file is planned, converted, copied,
 *   or listed as needing a person.
 */

export type MoveAction =
  | { kind: "copy"; from: string; to: string }
  | { kind: "header"; from: string; to: string }
  | { kind: "extract"; from: string; to: string; carrier: "md" | "slides" | "paged" }
  | { kind: "skip"; from: string; reason: string };

const SLOT_DIRS = ["concepts", "study-guide", "slides", "assessment-support", "practice"];
const SKIP_ROOT = new Set([".git", "node_modules"]);
const GENERATED = [/^\.github\//, /^\.alembic\//, /^alembic\.json$/, /^provenance\/coursewerk\//];

/** Plan one file of the old public (`repo = "public"`) or private repo. */
export function planFile(repo: "public" | "private", path: string): MoveAction {
  const first = path.split("/")[0]!;
  if (SKIP_ROOT.has(first)) return { kind: "skip", from: path, reason: "not course content" };
  if (repo === "private" && !path.startsWith("private/")) {
    // The old private repo held private/... plus its own README/manifest copies.
    return { kind: "skip", from: path, reason: "outside private/ in the private repo (check by hand)" };
  }
  if (GENERATED.some((r) => r.test(path))) {
    return { kind: "skip", from: path, reason: "regenerated by Alembic (manifest, workflows, Coursewerk record)" };
  }
  const html = /^(.*)\.(md|slides|paged)\.html$/i.exec(path);
  if (html) {
    const carrier = html[2]!.toLowerCase() as "md" | "slides" | "paged";
    return { kind: "extract", from: path, to: `${html[1]}${carrier === "md" ? ".md" : `.${carrier}.md`}`, carrier };
  }
  if (/^slides\/[^/]+\.md$/i.test(path) && !/\.slides\.md$/i.test(path)) {
    return { kind: "header", from: path, to: path.replace(/\.md$/i, ".slides.md") };
  }
  if (SLOT_DIRS.includes(first) && /\.md$/i.test(path)) return { kind: "header", from: path, to: path };
  return { kind: "copy", from: path, to: path };
}

const HAS_HEADER = /^﻿?\{\{nyml[ \t]*\r?\n/;

/**
 * A 0.x deck source: its settings live in a `<!-- deck … -->` block. Such a
 * deck must go through orz-slides' own upgrade (settings into the format-1
 * header), not just get a header: the website build refuses the block.
 */
export const isLegacyDeck = (text: string): boolean => /<!--\s*deck\b/.test(text);

/** Add an FC-18 format-1 header to a lean text, keeping its body exactly. */
export function addHeader(text: string, o: { title?: string | null; uid?: string | null }): string {
  if (HAS_HEADER.test(text)) return text;
  const heading = /^#[ \t]+(.+?)[ \t#]*$/m.exec(text)?.[1];
  const title = (o.title ?? heading ?? "").replace(/\}\}/g, "} }").replace(/[\r\n]+/g, " ").trim();
  const lines = ["{{nyml", "kind: document", "format: 1"];
  if (title) lines.push(`title: ${title}`);
  if (o.uid && /^doc-[0-9a-z]{10,32}$/.test(o.uid)) lines.push(`uid: ${o.uid}`);
  lines.push("}}", "", "");
  return lines.join("\n") + text.replace(/^﻿/, "");
}

/** Two plans writing the same target (e.g. `a.md` and `a.md.html`) need a person. */
export function findCollisions(actions: MoveAction[]): Array<{ to: string; from: string[] }> {
  const by = new Map<string, string[]>();
  for (const a of actions) if (a.kind !== "skip") by.set(a.to, [...(by.get(a.to) ?? []), a.from]);
  return [...by].filter(([, f]) => f.length > 1).map(([to, from]) => ({ to, from }));
}
