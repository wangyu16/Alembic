#!/usr/bin/env node
/**
 * Regenerate packages/renderer/src/theme-css.ts from the orz-markdown version
 * the renderer depends on (its own node_modules), so the CSS Alembic inlines
 * is exactly the kit's shipped `themes/<id>.css` — no hand edits.
 *
 * Why vendored rather than read at runtime: the renderer runs inside Vercel
 * serverless functions, where reading `orz-markdown/themes/*.css` from disk
 * depends on file tracing; a generated TS string has no such risk. The test
 * `theme-css.test.ts` fails when this file drifts from the installed kit —
 * re-run this script after bumping orz-markdown:
 *
 *   node scripts/vendor-themes.mjs
 *
 * Each constant is: the theme's font @imports (hoisted, valid CSS), then
 * common.css, then the theme body without its imports.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const renderer = join(root, "packages/renderer");
const require = createRequire(join(renderer, "package.json"));
const themes = dirname(require.resolve("orz-markdown/themes/common.css"));
const kitVersion = JSON.parse(readFileSync(join(themes, "..", "package.json"), "utf8")).version;

const IMPORT = /^@import[^\n]*\n/gm;
const common = readFileSync(join(themes, "common.css"), "utf8");

function combined(id) {
  const css = readFileSync(join(themes, `${id}.css`), "utf8");
  const imports = (css.match(IMPORT) ?? []).filter((l) => !l.includes("common.css")).join("");
  return `${imports}\n/* --- common.css (inlined) --- */\n${common}\n/* --- ${id}.css --- */\n${css.replace(IMPORT, "")}`;
}

const out = `// GENERATED by scripts/vendor-themes.mjs from orz-markdown@${kitVersion}
// (themes/dark-elegant-1.css, themes/light-academic-1.css + themes/common.css),
// MIT, same author. Do not edit by hand: bump orz-markdown, then re-run the
// script; theme-css.test.ts checks this file against the installed kit.
// Rendered content must be wrapped in <div class="markdown-body">.

/** The orz-markdown version these stylesheets were generated from. */
export const VENDORED_THEMES_VERSION = ${JSON.stringify(kitVersion)};

/** orz-markdown's \`dark-elegant-1\` theme with common.css inlined. */
export const ORZ_DARK_ELEGANT_CSS = ${JSON.stringify(combined("dark-elegant-1"))};

/** orz-markdown's \`light-academic-1\` theme with common.css inlined. */
export const ORZ_LIGHT_ACADEMIC_CSS = ${JSON.stringify(combined("light-academic-1"))};

export type RenderTheme = "dark" | "light";

/**
 * Derive a dark/light scheme from an orz theme id (or a legacy "dark"/"light"
 * value). orz theme ids are prefixed by scheme (e.g. \`dark-elegant-1\`,
 * \`light-neat-3\`). Used to theme the Alembic-rendered course-home hub to match
 * the course's chosen study-guide theme.
 */
export function themeScheme(theme: string | undefined): RenderTheme {
  return theme && theme.toLowerCase().startsWith("dark") ? "dark" : "light";
}

/** The vendored orz-markdown CSS for a render theme (dark-elegant / light-academic). */
export function themeCss(theme: RenderTheme = "dark"): string {
  return theme === "light" ? ORZ_LIGHT_ACADEMIC_CSS : ORZ_DARK_ELEGANT_CSS;
}
`;

const target = join(renderer, "src/theme-css.ts");
writeFileSync(target, out);
console.log(`Wrote ${target} from orz-markdown@${kitVersion}.`);
