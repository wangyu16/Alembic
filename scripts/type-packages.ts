/**
 * Vendored type packages (family docs/SITE-TYPE-CONTRACT.md §3, FD-11).
 *
 *   npx tsx scripts/type-packages.ts vendor <folder> --repo <repo> --tag <tag> --commit <sha>
 *     Copies a type package's tagged definition folder into
 *     type-packages/<type>/<major>/ and records where it came from.
 *   npx tsx scripts/type-packages.ts bundle
 *     Checks every vendored definition against the schema and writes
 *     packages/package-contract/src/site-type/bundled.generated.ts (the
 *     definitions and their files as data, so the contract package stays
 *     pure) and the JSON Schema under packages/package-contract/schema/.
 *   npx tsx scripts/type-packages.ts stand-in <type>/<major> --note <text>
 *     Records a folder written in Alembic itself as a stand-in for the type
 *     package's release (until the real one is vendored over it).
 *   npx tsx scripts/type-packages.ts check
 *     Fails if a vendored folder doesn't match its recorded checksum, or the
 *     bundle is out of date (run by the contract package's tests too).
 */
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { parseSiteType, SiteTypeSchema } from "../packages/package-contract/src/site-type/schema";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const vendorRoot = join(root, "type-packages");
const bundleFile = join(root, "packages/package-contract/src/site-type/bundled.generated.ts");
const schemaFile = join(root, "packages/package-contract/schema/alembic.site-type-1.schema.json");

/** Every file under a folder (sorted, relative), except the provenance record itself. */
function filesOf(dir: string): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else out.push(relative(dir, p).split("\\").join("/"));
    }
  };
  walk(dir);
  return out.filter((f) => f !== "VENDOR.json");
}

/** sha256 over each file's path and bytes, in order. */
export function checksumOf(dir: string): string {
  const h = createHash("sha256");
  for (const f of filesOf(dir)) h.update(`${f}\u0000`).update(readFileSync(join(dir, f))).update("\u0000");
  return h.digest("hex");
}

function definitionDirs(): string[] {
  if (!existsSync(vendorRoot)) return [];
  return readdirSync(vendorRoot).sort().flatMap((type) => readdirSync(join(vendorRoot, type)).sort().map((major) => join(vendorRoot, type, major)));
}

function vendor(src: string, meta: Record<string, string>): void {
  const raw = JSON.parse(readFileSync(join(src, "site-type.json"), "utf8"));
  const parsed = parseSiteType(raw);
  if (!parsed.ok) throw new Error(`the definition can't be applied:\n- ${parsed.problems.join("\n- ")}`);
  const major = parsed.def.version.split(".")[0]!;
  const dest = join(vendorRoot, parsed.def.type, major);
  rmSync(dest, { recursive: true, force: true });
  mkdirSync(dest, { recursive: true });
  cpSync(src, dest, { recursive: true, filter: (p) => !p.split(/[\\/]/).some((part) => part.startsWith(".") && part !== ".") });
  writeFileSync(join(dest, "VENDOR.json"), JSON.stringify({ ...meta, version: parsed.def.version, copiedAt: new Date().toISOString(), checksum: checksumOf(dest) }, null, 2) + "\n");
  console.log(`vendored ${parsed.def.type}@${parsed.def.version} into ${relative(root, dest)}`);
}

function bundleText(): string {
  const entries = definitionDirs().map((dir) => {
    const raw = JSON.parse(readFileSync(join(dir, "site-type.json"), "utf8"));
    const parsed = parseSiteType(raw);
    if (!parsed.ok) throw new Error(`${relative(root, dir)} can't be applied:\n- ${parsed.problems.join("\n- ")}`);
    const vendorMeta = JSON.parse(readFileSync(join(dir, "VENDOR.json"), "utf8"));
    if (vendorMeta.checksum !== checksumOf(dir)) throw new Error(`${relative(root, dir)} changed since it was vendored: vendor it again`);
    const files: Record<string, string> = {};
    for (const f of filesOf(dir)) if (f !== "site-type.json") files[f] = readFileSync(join(dir, f), "utf8");
    return { key: `${parsed.def.type}@${parsed.def.version.split(".")[0]}`, definition: raw, files, vendor: vendorMeta };
  });
  return `// GENERATED by scripts/type-packages.ts bundle: DO NOT EDIT BY HAND.
// The vendored type packages (family docs/SITE-TYPE-CONTRACT.md §3), as data.
/* eslint-disable */
export const BUNDLED_TYPE_PACKAGES: Readonly<Record<string, { definition: unknown; files: Readonly<Record<string, string>>; vendor: Readonly<Record<string, string>> }>> = ${JSON.stringify(Object.fromEntries(entries.map((e) => [e.key, { definition: e.definition, files: e.files, vendor: e.vendor }])), null, 2)};
`;
}

const schemaText = () => JSON.stringify({ $id: "https://github.com/wangyu16/Alembic/packages/package-contract/schema/alembic.site-type-1.schema.json", title: "Alembic site type definition, schema 1", ...z.toJSONSchema(SiteTypeSchema) }, null, 2) + "\n";

const [cmd, ...rest] = process.argv.slice(2);
const flag = (name: string) => { const i = rest.indexOf(`--${name}`); return i >= 0 ? rest[i + 1] : undefined; };
if (cmd === "vendor") {
  const src = rest[0];
  if (!src || src.startsWith("--")) throw new Error("vendor <folder> --repo <repo> --tag <tag> --commit <sha>");
  vendor(src, { source: "type-package", repo: flag("repo") ?? "", tag: flag("tag") ?? "", commit: flag("commit") ?? "" });
} else if (cmd === "stand-in") {
  const dir = join(vendorRoot, rest[0] ?? "");
  if (!rest[0] || !existsSync(join(dir, "site-type.json"))) throw new Error("stand-in <type>/<major> --note <text>");
  const parsed = parseSiteType(JSON.parse(readFileSync(join(dir, "site-type.json"), "utf8")));
  if (!parsed.ok) throw new Error(`the definition can't be applied:\n- ${parsed.problems.join("\n- ")}`);
  writeFileSync(join(dir, "VENDOR.json"), JSON.stringify({ source: "alembic-stand-in", note: flag("note") ?? "", version: parsed.def.version, checksum: checksumOf(dir) }, null, 2) + "\n");
  console.log(`recorded ${rest[0]} as a stand-in`);
} else if (cmd === "bundle") {
  mkdirSync(dirname(schemaFile), { recursive: true });
  writeFileSync(bundleFile, bundleText());
  writeFileSync(schemaFile, schemaText());
  console.log(`wrote ${relative(root, bundleFile)} and ${relative(root, schemaFile)}`);
} else if (cmd === "check") {
  const stale = readFileSync(bundleFile, "utf8") !== bundleText() || readFileSync(schemaFile, "utf8") !== schemaText();
  if (stale) { console.error("the bundle or the schema is out of date: run `npx tsx scripts/type-packages.ts bundle`"); process.exit(1); }
  console.log("type packages: up to date");
} else {
  console.error("usage: type-packages.ts vendor|bundle|check");
  process.exit(2);
}
